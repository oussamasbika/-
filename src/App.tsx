      arVoices.find(v => isFemaleVoice(v) && isNaturalOrGoogle(v)) ||
      arVoices.find(v => isFemaleVoice(v)) ||
      arVoices.find(v => isNaturalOrGoogle(v) && !isMaleVoice(v)) ||
      arVoices.find(v => !isMaleVoice(v)) ||
      arVoices[0];

